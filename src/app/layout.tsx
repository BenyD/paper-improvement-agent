import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import "./globals.css";
import { Toaster } from "@/components/ui/sonner";

// Registered as --font-sans so the shadcn/Tailwind theme picks Geist up
// directly (its `--font-sans: var(--font-sans)` mapping otherwise falls
// back to the system font).
const geistSans = Geist({
  variable: "--font-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: {
    default: "Paper Improvement Agent",
    template: "%s · Paper Improvement Agent",
  },
  description:
    "Upload a research paper, get a peer review grounded in real academic search, and improve it without losing a citation.",
};

export default function RootLayout({ children }: LayoutProps<"/">) {
  return (
    <html
      lang="en"
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
    >
      <body className="min-h-full flex flex-col">
        {children}
        <Toaster />
      </body>
    </html>
  );
}
